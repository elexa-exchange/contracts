import { promises as fs } from "fs";
import path from "path";
import hre from "hardhat";

/**
 * Writes the compiled ElexaEscrow ABI to `abi/ElexaEscrow.json`, so consumers
 * have a checked-in copy that cannot silently drift from the deployed contract.
 * Run after any change to the contract's interface.
 *
 * Applications that embed the ABI can be updated in the same pass by pointing
 * ABI_EXPORT_JSON and/or ABI_EXPORT_TS at them from a .env file. Both are
 * optional, and both take a path relative to this directory.
 */
async function main() {
  const artifact = await hre.artifacts.readArtifact("ElexaEscrow");
  const abi = JSON.stringify(artifact.abi, null, 2);
  const root = path.resolve(__dirname, "..");

  const json = `${abi}\n`;
  const ts =
    `// Generated by scripts/export-abi.ts — do not edit by hand.\n` +
    `export const elexaEscrowAbi = ${abi} as const;\n`;

  const targets: Array<[string, string]> = [
    [path.resolve(root, "abi", "ElexaEscrow.json"), json],
  ];

  // Optional extra destinations, one path each. Absent means "not wanted".
  const extras: Array<[string | undefined, string]> = [
    [process.env.ABI_EXPORT_JSON, json],
    [process.env.ABI_EXPORT_TS, ts],
  ];
  for (const [target, contents] of extras) {
    if (target?.trim()) targets.push([path.resolve(root, target.trim()), contents]);
  }

  for (const [target, contents] of targets) {
    await fs.mkdir(path.dirname(target), { recursive: true });
    await fs.writeFile(target, contents);
    console.log(`wrote ${path.relative(root, target)}`);
  }
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
